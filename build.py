#!/usr/bin/env python3
"""
BalVoice static site builder.

Composes every page in src/pages/ with the shared partials in src/partials/
and writes a deployable site to dist/. No dependencies beyond Python 3.8+.

    python3 build.py

Configuration comes from environment variables or a .env file next to this
script (see .env.example). Only PUBLIC values belong here — the Supabase anon
key is designed to be public; never put a service-role key or the BMS API key
in .env for the website.

Page files start with a metadata block of HTML comments:

    <!-- title: Page title -->
    <!-- description: Meta description for search engines -->
    <!-- nav: key of the active navigation item -->
    <!-- layout: site | app | auth   (optional, defaults to site) -->
    <!-- robots: index,follow        (optional) -->
"""
from __future__ import annotations

import datetime
import json
import os
import pathlib
import re
import shutil
from urllib.parse import urlparse

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "src"
OUT = ROOT / "dist"
SITE_NAME = "BalVoice"

META_RE = re.compile(r"<!--\s*(\w+)\s*:\s*(.*?)\s*-->")


def load_env() -> dict:
    """Read .env (KEY=value lines) and let real environment variables override it."""
    env: dict[str, str] = {}
    path = ROOT / ".env"
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            env[k.strip()] = v.strip().strip('"').strip("'")
    for k in ("SITE_URL", "SUPABASE_URL", "SUPABASE_ANON_KEY", "TURNSTILE_SITE_KEY", "ALLOWED_PHONE_COUNTRIES"):
        if os.environ.get(k):
            env[k] = os.environ[k]
    return env


ENV = load_env()
SITE_URL = ENV.get("SITE_URL", "https://www.example.com").rstrip("/")
SUPABASE_URL = ENV.get("SUPABASE_URL", "").rstrip("/")
SUPABASE_ANON_KEY = ENV.get("SUPABASE_ANON_KEY", "")
TURNSTILE_SITE_KEY = ENV.get("TURNSTILE_SITE_KEY", "")
ALLOWED_PHONE_COUNTRIES = ENV.get("ALLOWED_PHONE_COUNTRIES", "GH")


def csp() -> str:
    """Content Security Policy, widened only for the services that are configured."""
    connect = ["'self'"]
    script = ["'self'"]
    frame = ["'none'"]
    media = ["'self'", "blob:"]
    if SUPABASE_URL:
        host = urlparse(SUPABASE_URL).netloc
        connect += [f"https://{host}", f"wss://{host}"]
        media.append(f"https://{host}")  # signed URLs for campaign audio
    if TURNSTILE_SITE_KEY:
        script.append("https://challenges.cloudflare.com")
        frame = ["https://challenges.cloudflare.com"]
    return (
        "default-src 'self'; "
        f"script-src {' '.join(script)}; "
        "style-src 'self' https://fonts.googleapis.com; "
        "font-src 'self' https://fonts.gstatic.com; "
        "img-src 'self' data:; "
        f"media-src {' '.join(media)}; "
        f"connect-src {' '.join(connect)}; "
        f"frame-src {' '.join(frame)}; "
        "form-action 'self'; base-uri 'self'; object-src 'none'"
    )


def read(path: pathlib.Path) -> str:
    return path.read_text(encoding="utf-8")


def parse_page(text: str) -> tuple[dict, str]:
    meta: dict[str, str] = {}
    body_lines = []
    in_header = True
    for line in text.splitlines():
        m = META_RE.fullmatch(line.strip()) if in_header else None
        if m:
            meta[m.group(1)] = m.group(2)
            continue
        if line.strip():
            in_header = False
        if not in_header:
            body_lines.append(line)
    return meta, "\n".join(body_lines)


def mark_active(html: str, key: str) -> str:
    """Add aria-current to nav links whose data-nav matches the page key."""
    if not key:
        return html
    return re.sub(rf'data-nav="{re.escape(key)}"', f'data-nav="{key}" aria-current="page"', html)


def write_config() -> None:
    """Public runtime configuration read by assets/js/auth.js."""
    config = {
        "siteUrl": SITE_URL,
        "supabaseUrl": SUPABASE_URL,
        "supabaseAnonKey": SUPABASE_ANON_KEY,
        "turnstileSiteKey": TURNSTILE_SITE_KEY,
        "allowedPhoneCountries": [c.strip().upper() for c in ALLOWED_PHONE_COUNTRIES.split(",") if c.strip()],
    }
    js = (
        "/* Generated by build.py from .env — do not edit. Public values only. */\n"
        f"window.BALVOICE_CONFIG = Object.freeze({json.dumps(config, indent=2)});\n"
    )
    (OUT / "assets" / "js" / "config.js").write_text(js, encoding="utf-8")


def build() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    shutil.copytree(SRC / "assets", OUT / "assets")
    write_config()
    policy = csp()
    for static in (SRC / "static").iterdir():
        text = read(static).replace("{{csp}}", policy)
        (OUT / static.name).write_text(text, encoding="utf-8")

    partials = {p.stem: read(p) for p in (SRC / "partials").glob("*.html")}
    year = str(datetime.date.today().year)
    pages = sorted((SRC / "pages").glob("*.html"))
    sitemap_urls = []

    for page in pages:
        meta, body = parse_page(read(page))
        layout = meta.get("layout", "site")
        nav_key = meta.get("nav", "")
        slug = page.name
        url = f"{SITE_URL}/" if slug == "index.html" else f"{SITE_URL}/{slug}"

        head = (
            partials["head"]
            .replace("{{title}}", meta.get("title", SITE_NAME))
            .replace("{{description}}", meta.get("description", ""))
            .replace("{{canonical}}", url)
            .replace("{{site_name}}", SITE_NAME)
            .replace("{{robots}}", meta.get("robots", "index,follow"))
            .replace("{{csp}}", policy)
        )

        if layout in ("app", "auth"):
            html = partials[layout].replace("{{head}}", head).replace("{{body}}", body).replace("{{year}}", year)
        else:
            header = mark_active(partials["header"], nav_key)
            footer = partials["footer"].replace("{{year}}", year)
            html = (
                partials["site"]
                .replace("{{head}}", head)
                .replace("{{header}}", header)
                .replace("{{body}}", body)
                .replace("{{footer}}", footer)
            )

        (OUT / slug).write_text(html, encoding="utf-8")
        if meta.get("robots", "index").startswith("index"):
            sitemap_urls.append(url)
        print(f"  built {slug}")

    today = datetime.date.today().isoformat()
    entries = "\n".join(f"  <url><loc>{u}</loc><lastmod>{today}</lastmod></url>" for u in sitemap_urls)
    (OUT / "sitemap.xml").write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{entries}\n</urlset>\n",
        encoding="utf-8",
    )
    (OUT / "robots.txt").write_text(
        "User-agent: *\n"
        "Disallow: /dashboard.html\nDisallow: /auth-callback.html\nDisallow: /reset-password.html\n"
        f"Sitemap: {SITE_URL}/sitemap.xml\n",
        encoding="utf-8",
    )
    mode = "Supabase connected" if SUPABASE_URL and SUPABASE_ANON_KEY else "demo mode (no Supabase settings in .env)"
    print(f"Done. {len(pages)} pages written to {OUT.relative_to(ROOT)}/ — {mode}")


if __name__ == "__main__":
    build()
